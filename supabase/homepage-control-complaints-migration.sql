create table if not exists public.complaints (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text not null,
  message text not null,
  status text not null default 'new' check (status in ('new','in_progress','resolved')),
  created_at timestamptz not null default now(),
  constraint complaints_name_length check (char_length(trim(name)) between 1 and 120),
  constraint complaints_email_length check (char_length(trim(email)) between 5 and 254),
  constraint complaints_subject_length check (char_length(trim(subject)) between 1 and 180),
  constraint complaints_message_length check (char_length(trim(message)) between 5 and 5000)
);
create index if not exists complaints_created_at_idx on public.complaints(created_at desc);
create index if not exists complaints_status_created_idx on public.complaints(status, created_at desc);
alter table public.complaints enable row level security;
drop policy if exists "Visitors can send complaints" on public.complaints;
drop policy if exists "Admins manage complaints" on public.complaints;
create policy "Visitors can send complaints" on public.complaints
  for insert to anon, authenticated with check (
    char_length(trim(name)) between 1 and 120 and
    char_length(trim(email)) between 5 and 254 and
    position('@' in email) > 1 and
    char_length(trim(subject)) between 1 and 180 and
    char_length(trim(message)) between 5 and 5000 and
    status = 'new'
  );
create policy "Admins manage complaints" on public.complaints
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
grant insert on public.complaints to anon, authenticated;
grant select, update, delete on public.complaints to authenticated;
grant usage, select on sequence public.complaints_id_seq to anon, authenticated;

