-- 1) Extend prompts without removing legacy columns.
alter table public.prompts
  add column if not exists content_text text not null default '',
  add column if not exists about_text text not null default '',
  add column if not exists how_to_use text not null default '',
  add column if not exists prompt_variants jsonb not null default '[]'::jsonb,
  add column if not exists related_prompts jsonb not null default '[]'::jsonb;

update public.prompts
set content_text = coalesce(nullif(content_text, ''), prompt_en, '')
where content_text = '';

-- 2) Homepage sections managed by the Admin Panel.
create table if not exists public.homepage_sections (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  placement text not null check (placement in (
    'after_trending','after_latest','after_photo','after_video','after_categories','after_howto'
  )),
  section_type text not null check (section_type in ('cards','info')),
  content text not null default '',
  items jsonb not null default '[]'::jsonb,
  is_published boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists homepage_sections_position_idx
  on public.homepage_sections(placement, sort_order, id);
alter table public.homepage_sections enable row level security;
drop policy if exists "Published homepage sections are visible" on public.homepage_sections;
drop policy if exists "Admins manage homepage sections" on public.homepage_sections;
create policy "Published homepage sections are visible"
  on public.homepage_sections for select to anon, authenticated
  using (is_published = true or public.is_admin());
create policy "Admins manage homepage sections"
  on public.homepage_sections for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
grant select on public.homepage_sections to anon, authenticated;
grant insert, update, delete on public.homepage_sections to authenticated;
grant usage, select on sequence public.homepage_sections_id_seq to authenticated;

-- 3) Privacy-conscious page-view analytics. No IP address, name or email is collected.
create table if not exists public.page_views (
  id bigint generated by default as identity primary key,
  page_path text not null,
  prompt_id bigint references public.prompts(id) on delete set null,
  visitor_id uuid not null,
  created_at timestamptz not null default now(),
  constraint page_views_page_path_length check (char_length(page_path) between 1 and 400)
);
create index if not exists page_views_created_at_idx on public.page_views(created_at desc);
create index if not exists page_views_prompt_created_idx on public.page_views(prompt_id, created_at desc);
create index if not exists page_views_visitor_created_idx on public.page_views(visitor_id, created_at desc);
alter table public.page_views enable row level security;
drop policy if exists "Public can record page views" on public.page_views;
drop policy if exists "Admins can read page views" on public.page_views;
create policy "Public can record page views"
  on public.page_views for insert to anon, authenticated
  with check (
    char_length(page_path) between 1 and 400
    and (prompt_id is null or exists (
      select 1 from public.prompts p where p.id = prompt_id and p.status = 'published'
    ))
  );
create policy "Admins can read page views"
  on public.page_views for select to authenticated
  using (public.is_admin());
grant insert on public.page_views to anon, authenticated;
grant select on public.page_views to authenticated;
grant usage, select on sequence public.page_views_id_seq to anon, authenticated;

-- 4) Aggregated analytics functions. Results are restricted to verified admins.
create or replace function public.get_analytics_overview()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  today_start timestamptz := date_trunc('day', now() at time zone 'Asia/Kolkata') at time zone 'Asia/Kolkata';
  month_start timestamptz := date_trunc('month', now() at time zone 'Asia/Kolkata') at time zone 'Asia/Kolkata';
  year_start timestamptz := date_trunc('year', now() at time zone 'Asia/Kolkata') at time zone 'Asia/Kolkata';
  result jsonb;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select jsonb_build_object(
    'total_visits', count(*),
    'today_visits', count(*) filter (where created_at >= today_start),
    'yesterday_visits', count(*) filter (where created_at >= today_start - interval '1 day' and created_at < today_start),
    'month_visits', count(*) filter (where created_at >= month_start),
    'year_visits', count(*) filter (where created_at >= year_start),
    'total_visitors', count(distinct visitor_id),
    'today_visitors', count(distinct visitor_id) filter (where created_at >= today_start),
    'yesterday_visitors', count(distinct visitor_id) filter (where created_at >= today_start - interval '1 day' and created_at < today_start),
    'month_visitors', count(distinct visitor_id) filter (where created_at >= month_start),
    'year_visitors', count(distinct visitor_id) filter (where created_at >= year_start)
  ) into result from public.page_views;
  return coalesce(result, '{}'::jsonb);
end;
$$;

create or replace function public.get_analytics_yearly()
returns table(year integer, visits bigint, visitors bigint)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  return query
  select extract(year from pv.created_at at time zone 'Asia/Kolkata')::integer,
         count(*)::bigint, count(distinct pv.visitor_id)::bigint
  from public.page_views pv
  group by 1 order by 1 desc;
end;
$$;

create or replace function public.get_prompt_view_stats()
returns table(prompt_id bigint, title text, year integer, views bigint, visitors bigint)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  return query
  select p.id, p.title,
         extract(year from pv.created_at at time zone 'Asia/Kolkata')::integer,
         count(*)::bigint, count(distinct pv.visitor_id)::bigint
  from public.page_views pv
  join public.prompts p on p.id = pv.prompt_id
  group by p.id, p.title, 3
  order by 3 desc, 4 desc;
end;
$$;

revoke all on function public.get_analytics_overview() from public;
revoke all on function public.get_analytics_yearly() from public;
revoke all on function public.get_prompt_view_stats() from public;
grant execute on function public.get_analytics_overview() to authenticated;
grant execute on function public.get_analytics_yearly() to authenticated;
grant execute on function public.get_prompt_view_stats() to authenticated;

